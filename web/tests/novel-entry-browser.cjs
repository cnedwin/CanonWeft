// Run only from the isolated MySQL integration fixture. No API mocks.
const { chromium, expect } = require("@playwright/test");

(async () => {
  const origin = process.argv[2];
  if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw new Error("isolated loopback server required");
  const browser = await chromium.launch();
  let page;
  try {
    page = await browser.newPage();
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(origin);
    await page.getByLabel("用户名", { exact: true }).fill("owner");
    await page.getByLabel("密码", { exact: true }).fill("test-owner-password-123");
    await page.getByRole("button", { name: "登录", exact: true }).click();
    await page.getByRole("button", { name: "新建小说", exact: true }).click();
    await page.getByRole("button", { name: "从新的创作想法开始" }).click();
    await page.getByLabel("书名", { exact: true }).fill("雾城药师");
    await page.getByLabel("题材", { exact: true }).fill("悬疑奇幻");
    await page.getByRole("button", { name: "下一步", exact: true }).click();
    await page.getByLabel("核心梗概或创作想法").fill("医者调查雾城的失踪旧案");
    await page.getByLabel("主线目标与主要冲突").fill("找回师父，同时保护城中的普通人");
    await page.getByLabel("世界背景", { exact: true }).fill("被浓雾围困的药师之城");
    await page.getByRole("button", { name: "下一步", exact: true }).click();
    await page.getByRole("button", { name: "下一步", exact: true }).click();
    await page.getByLabel("主角设置方式").selectOption("manual");
    await page.getByRole("button", { name: "添加一位主角" }).click();
    await page.getByLabel("姓名或暂名").fill("林舟");
    await page.getByLabel("身份与职业").fill("医师");
    await page.getByLabel("核心目标", { exact: true }).fill("找到失踪师父");
    await page.getByLabel("人物背景").fill("自幼在药师会长大");
    await page.getByLabel("性格", { exact: true }).fill("沉静而执着");
    await page.getByRole("button", { name: "下一步", exact: true }).click();
    await page.getByRole("combobox", { name: /^创作方式/ }).selectOption("manual");
    await page.getByLabel("我确认采用以上小说设置").check();
    await page.getByRole("button", { name: "确认创建小说", exact: true }).click();
    await expect(page.getByRole("heading", { name: "雾城药师", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "修改小说设置与查看历史" }).click();
    await expect(page.getByRole("heading", { name: "修改小说设置", exact: true })).toBeVisible();
    await page.getByLabel("书名", { exact: true }).fill("雾城药师修订版");
    await page.getByLabel("叙事视角", { exact: true }).fill("第一人称");
    await page.getByRole("button", { name: "查看修改差异", exact: true }).click();
    await expect(page.getByRole("region", { name: "设置修改差异" })).toContainText("雾城药师修订版");
    await page.getByLabel("我已查看差异，确认采用这些设置").check();
    await page.getByRole("button", { name: "确认保存新版本", exact: true }).click();
    await expect(page.getByRole("heading", { name: "雾城药师修订版", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "本书角色与关系", exact: true }).click();
    await expect(page.getByRole("heading", { name: "角色库", exact: true })).toBeVisible();
    await expect(page.getByRole("searchbox", { name: "搜索角色" })).toBeFocused();
    await page.getByRole("button", { name: /林舟/ }).first().click();
    await expect(page.getByRole("heading", { name: "林舟 · 角色详情", exact: true })).toBeFocused();
    const savedCharacter = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/draft") && response.request().postData()?.includes("林知舟"));
    await page.getByLabel("角色姓名", { exact: true }).fill("林知舟");
    // The existing role editor autosaves without publishing the candidate.
    expect((await savedCharacter).status()).toBe(200);
    await expect(page.getByText("草稿已自动暂存，尚未采用", { exact: true })).toBeVisible();
    await page.reload();
    await page.getByRole("button", { name: "雾城药师修订版 · 继续完善世界与故事", exact: true }).click();
    await page.getByRole("button", { name: "编辑本书世界与角色" }).click();
    await page.getByRole("button", { name: /林知舟/ }).first().click();
    await expect(page.getByLabel("角色姓名", { exact: true })).toHaveValue("林知舟");
    await page.getByRole("button", { name: "返回项目书架", exact: true }).click();
    await page.getByRole("button", { name: "管理本书资料", exact: true }).click();
    await expect(page.getByRole("heading", { name: "本书创作资料", exact: true })).toBeVisible();
    const original = "# 作者规划\n第三卷揭示师父仍然活着。🌙";
    await page.getByLabel("上传资料文件").setInputFiles({ name: "故事方向.md", mimeType: "text/markdown", buffer: Buffer.from(original) });
    await expect(page.getByLabel("导入内容 · 可修改")).toHaveValue(original);
    const imported = page.locator(".source-import");
    await expect(imported.getByRole("combobox", { name: "知识空间", exact: true })).toHaveValue("working");
    const edited = "作者修订：第四卷揭示师父仍然活着。";
    await page.getByLabel("导入内容 · 可修改").fill(edited);
    await imported.getByRole("combobox", { name: "知识空间", exact: true }).selectOption("methods");
    await expect(page.getByTestId("import-draft-status")).toHaveText("导入草稿已自动暂存");
    await page.reload();
    await page.getByRole("button", { name: "雾城药师修订版 · 继续完善世界与故事", exact: true }).click();
    await page.getByRole("button", { name: "管理本书资料", exact: true }).click();
    await expect(page.getByLabel("导入内容 · 可修改")).toHaveValue(edited);
    await expect(imported.getByRole("combobox", { name: "知识空间", exact: true })).toHaveValue("methods");
    const downloaded = page.waitForEvent("download");
    await page.getByRole("link", { name: "下载原文件核对" }).click();
    const file = await downloaded;
    expect(file.suggestedFilename()).toBe("故事方向.md");
    expect(await require("node:fs/promises").readFile(await file.path(), "utf8")).toBe(original);
    await imported.getByRole("combobox", { name: "知识空间", exact: true }).selectOption("working");
    await page.getByRole("button", { name: "保存文件内容候选", exact: true }).click();
    await expect(page.getByText("文件内容已保存为候选，请在下方检查、确认采用并发布。", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "检查联合候选", exact: true }).click();
    await expect(page.getByTestId("release-preview")).toContainText(edited);
    await page.getByRole("button", { name: "确认采用整组内容", exact: true }).click();
    await page.getByRole("button", { name: "发布整组内容", exact: true }).click();
    await expect(page.getByTestId("release-preview").getByRole("button", { name: "发布整组内容", exact: true })).toHaveCount(0);
    expect(errors).toEqual([]);
    console.log("Actual Vue + HTTP + MySQL: novel/settings/characters and file upload, parsing, private edit/use reload, original download, candidate adoption/publication passed; no model call.");
  } catch (error) {
    console.error(await page?.locator("body").innerText());
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
