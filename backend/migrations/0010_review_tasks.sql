CREATE TABLE IF NOT EXISTS platform_tasks (
 id CHAR(32) PRIMARY KEY, project_id CHAR(32) NOT NULL, branch_id CHAR(32) NOT NULL,
 candidate_id CHAR(32) NOT NULL, input_hash CHAR(64) NOT NULL, base_head CHAR(32) NOT NULL,
 actor_id CHAR(32) NOT NULL, state VARCHAR(40) NOT NULL DEFAULT 'QUEUED', reason VARCHAR(500) NOT NULL DEFAULT '',
 paused BOOLEAN NOT NULL DEFAULT FALSE, cancelled BOOLEAN NOT NULL DEFAULT FALSE, revision BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(project_id) REFERENCES projects(id), FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(candidate_id) REFERENCES ip_revisions(id), FOREIGN KEY(actor_id) REFERENCES users(id), INDEX(project_id,created_at)
) ENGINE=InnoDB;
