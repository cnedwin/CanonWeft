CREATE TABLE IF NOT EXISTS ingest_jobs (
 id CHAR(32) NOT NULL PRIMARY KEY,
 project_id CHAR(32) NOT NULL,
 branch_id CHAR(32) NOT NULL,
 actor_id CHAR(32) NOT NULL,
 operation_id VARCHAR(120) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 filename VARCHAR(160) NOT NULL,
 source_hash CHAR(64) NOT NULL,
 source_size BIGINT NOT NULL,
 parser_revision VARCHAR(100) NOT NULL,
 ocr_mode VARCHAR(16) NOT NULL,
 progress MEDIUMTEXT NOT NULL,
 progress_hash CHAR(64) NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
 paused BOOLEAN NOT NULL DEFAULT FALSE,
 cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
 revision BIGINT NOT NULL DEFAULT 1,
 reason VARCHAR(64) NOT NULL DEFAULT '',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY(actor_id,operation_id),
 INDEX(project_id,branch_id,actor_id,created_at),
 FOREIGN KEY(project_id) REFERENCES projects(id),
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS import_drafts (
 import_id CHAR(32) NOT NULL,
 actor_id CHAR(32) NOT NULL,
 project_id CHAR(32) NOT NULL,
 revision BIGINT NOT NULL,
 payload MEDIUMTEXT NOT NULL,
 content_hash CHAR(64) NOT NULL,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(import_id,actor_id),
 FOREIGN KEY(import_id) REFERENCES source_imports(id),
 FOREIGN KEY(actor_id) REFERENCES users(id),
 FOREIGN KEY(project_id) REFERENCES projects(id)
);
