CREATE TABLE IF NOT EXISTS recipe_runs (
 id CHAR(32) NOT NULL PRIMARY KEY,
 workspace_id CHAR(32) NOT NULL,
 project_id CHAR(32) NOT NULL,
 branch_id CHAR(32) NOT NULL,
 actor_id CHAR(32) NOT NULL,
 operation_id VARCHAR(120) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 frozen MEDIUMTEXT NOT NULL,
 frozen_hash CHAR(64) NOT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'PREPARED',
 revision BIGINT NOT NULL DEFAULT 1,
 paused BOOLEAN NOT NULL DEFAULT FALSE,
 cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
 restored_disabled BOOLEAN NOT NULL DEFAULT FALSE,
 reason VARCHAR(64) NOT NULL DEFAULT '',
 currency CHAR(3) NOT NULL,
 budget_limit_micros BIGINT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY(actor_id,operation_id),
 INDEX(project_id,branch_id,created_at),
 FOREIGN KEY(workspace_id) REFERENCES workspaces(id),
 FOREIGN KEY(project_id) REFERENCES projects(id),
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS recipe_steps (
 id CHAR(32) NOT NULL PRIMARY KEY,
 run_id CHAR(32) NOT NULL,
 project_id CHAR(32) NOT NULL,
 step_key VARCHAR(80) NOT NULL,
 ordinal INT NOT NULL,
 attempt INT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 frozen MEDIUMTEXT NOT NULL,
 frozen_hash CHAR(64) NOT NULL,
 credential_ref VARCHAR(160) NOT NULL,
 generation_id CHAR(32) NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'WAITING',
 input_hash CHAR(64) NOT NULL DEFAULT '',
 output_hash CHAR(64) NOT NULL DEFAULT '',
 confirmed_hash CHAR(64) NOT NULL DEFAULT '',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY(run_id,step_key,attempt),
 UNIQUE KEY(generation_id),
 INDEX(run_id,active,ordinal),
 FOREIGN KEY(run_id) REFERENCES recipe_runs(id),
 FOREIGN KEY(project_id) REFERENCES projects(id),
 FOREIGN KEY(generation_id) REFERENCES generation_tasks(id)
);
