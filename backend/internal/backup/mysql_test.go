func randomID(t *testing.T) string {
	t.Helper()
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(b)
}
func testDatabase(t *testing.T) (*sql.DB, *mysql.Config, *sql.DB) {
	t.Helper()
	dsn := os.Getenv("STUDIO_BACKUP_TEST_ADMIN_DSN")
	if dsn == "" {
		t.Skip("isolated MySQL test requires STUDIO_BACKUP_TEST_ADMIN_DSN")
	}
	cfg, err := mysql.ParseDSN(dsn)
	if err != nil {
		t.Fatal("invalid test configuration")
	}
	cfg.DBName = ""
	cfg.ParseTime = true
	admin, err := sql.Open("mysql", cfg.FormatDSN())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { admin.Close() })
	name := "studio_backup_test_" + randomID(t)
	if _, err = admin.Exec("CREATE DATABASE `" + name + "` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci"); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if strings.HasPrefix(name, "studio_backup_test_") && hex32.MatchString(strings.TrimPrefix(name, "studio_backup_test_")) {
			_, err := admin.Exec("DROP DATABASE IF EXISTS `" + name + "`")
			if err != nil {
				t.Error(err)
			}
		}
	})
	cfg.DBName = name
	db, err := sql.Open("mysql", cfg.FormatDSN())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	if err = storage.RunMigrationsTo(context.Background(), db, supportedSchemaVersion); err != nil {
		t.Fatal(err)
	}
	return db, cfg, admin
}
func targetDSN(t *testing.T, cfg *mysql.Config, admin *sql.DB) string {
	t.Helper()
	target := cfg.Clone()
	target.DBName = "studio_restore_" + randomID(t)
	t.Cleanup(func() { // The random name is generated by this test; no user database is accepted.
		if restoreName.MatchString(target.DBName) {
			_, err := admin.Exec("DROP DATABASE IF EXISTS `" + target.DBName + "`")
			if err != nil {
				t.Error(err)
			}
		}
	})
	return target.FormatDSN()
}
func execTest(t *testing.T, db *sql.DB, q string, args ...any) {
	t.Helper()
	if _, err := db.Exec(q, args...); err != nil {
		t.Fatal(err)
	}
}
