	w, p := randomID(t), randomID(t)
	execTest(t, db, "INSERT INTO workspaces(id,name) VALUES(?,'deletion test')", w)
	execTest(t, db, "INSERT INTO projects(id,workspace_id,name) VALUES(?,?,'will be deleted')", p, w)
	ledger := provisionTestAuthority(t, db, admin)
	archive := filepath.Join(root, "before-deletion.zip")
	if _, err := Create(ctx, db, storage.LocalBlobs{Root: filepath.Join(root, "empty-source")}, archive); err != nil {
		t.Fatal(err)
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = tx.Exec("UPDATE projects SET deleted_at=UTC_TIMESTAMP(6) WHERE id=?", p); err != nil {
		t.Fatal(err)
	}
	if err = ledger.AppendTx(ctx, tx, authority.Event{Kind: authority.ProjectDeleted, ProjectID: p, ResourceID: p, ActorID: randomID(t)}); err != nil {
		t.Fatal(err)
	}
	if err = tx.Commit(); err != nil {
		t.Fatal(err)
	}
	if err = db.Close(); err != nil {
		t.Fatal(err)
	}
	execTest(t, admin, "DROP DATABASE `"+cfg.DBName+"`")
	opt := RestoreOptions{ArchivePath: archive, TargetDSN: targetDSN(t, cfg, admin), BlobRoot: filepath.Join(root, "target"), Authority: ProtectedAuthority{DB: admin, Ledger: ledger}}
